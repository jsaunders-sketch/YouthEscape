function convertWord(inputWord) {
            let newWord = "";

            for (let i = 0; i < inputWord.length; i++) {
                let character = inputWord[i];
                let asciiCode = character.charCodeAt(0);
                let newCharacter = String.fromCharCode(asciiCode + i + 1);

                newWord += newCharacter;

            }
    return newWord;
    }


